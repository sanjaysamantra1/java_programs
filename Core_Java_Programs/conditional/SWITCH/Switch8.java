class Switch8
{
public static void main(String arg[])
{
  switch(2+1) {
    case 5%2:
        System.out.println("case one");
        break;
    case 1+1:
        System.out.println("case two");
        break;
    case 5-2:
        System.out.println("case three");
        break;
    case 8/2:
        System.out.println("case four");
        break;

    default:
       System.out.println("default case");
       break;
     }
  }
}



