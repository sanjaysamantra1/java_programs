class Switch9
{
public static void main(String arg[])
{
  char m = 'c';

  switch(m)
  {
    case 'a':
        System.out.println("APPLE");
        break;
    case 'b':
        System.out.println("BUS");
        break;
    case 'c':
        System.out.println("CAT");
        break;
    case 'd':
        System.out.println("DOG");
        break;
    default:
       System.out.println("default case");
       break;
     }
  }
}



