// switch with String
// java 1.8

class Switch10
{
	public static void main(String[] args)
	{
		String s = "two";

		switch(s)
		{
		 case "one":
			System.out.println("Hello World!");
			break;
		 case "two":
			System.out.println("welcome ");
			break;
		 case "three":
			System.out.println("good morning");
			break;
		 default:
			 System.out.println("Default case");
	 		 break;

		}

	}
}


