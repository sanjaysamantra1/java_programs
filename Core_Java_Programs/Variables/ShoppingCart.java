
public class ShoppingCart {
    public static void main(String[] args) {

        // Declaration
        double price;
        int quantity;
        double total;

        // Initialization
        price = 799.50;
        quantity = 3;

        // Calculate total
        total = price * quantity;

        System.out.println("Product Price: " + price);
        System.out.println("Quantity: " + quantity);
        System.out.println("Total Amount: " + total);
    }
}
